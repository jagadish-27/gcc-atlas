export function metricsByCity(cityId: string): CityMetricValue[] {
  return cityMetrics.filter((m) => m.cityId === cityId);
}

export function getMetric(cityId: string, key: CityMetricValue['metricKey']): CityMetricValue | undefined {
  return cityMetrics.find((m) => m.cityId === cityId && m.metricKey === key);
}
